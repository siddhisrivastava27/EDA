--Measures Exploration--

-- Find total customers by countries
SELECT country,COUNT(Customer_key) AS total_customers
FROM [gold.dim_customers]
GROUP BY country
ORDER BY total_customers DESC;
 

-- Find total customers by gender
SELECT gender,COUNT(customer_key) as total_customers
FROM [gold.dim_customers]
GROUP BY gender
ORDER BY total_customers DESC;


-- Find total products by category
SELECT category,COUNT(product_key) AS total_products 
FROM [gold.dim_products]
GROUP BY category
ORDER BY total_products DESC;


-- What is the average costs in each category?
SELECT category, AVG(cost) AS avg_costs
FROM [gold.dim_products]
GROUP BY category
ORDER BY avg_costs DESC;


-- What is the total revenue generated for each category?
SELECT 
p.category,
SUM(f.sales_amount) total_revenue
FROM [gold.fact_sales] f
LEFT JOIN [gold.dim_products] p
ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC ;



-- Find total revenue is generated by each customer
SELECT 
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM [gold.fact_sales] f
LEFT JOIN [gold.dim_customers] c
    ON c.customer_key = f.customer_key
GROUP BY 
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;


--RANKING ANALYSIS--

--Which 5 product generate the highest revenue

SELECT TOP 5
p.product_name,
SUM(f.sales_amount) total_revenue
FROM [gold.fact_sales] f
LEFT JOIN [gold.dim_products] p
ON p.product_key = f.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC;



--What are the top 5 worst-performing products in terms of sales
SELECT TOP 5
p.product_name,
SUM(f.sales_amount) total_revenue
FROM [gold.fact_sales] f
LEFT JOIN [gold.dim_products] p
ON p.product_key = f.product_key
GROUP BY p.product_name
ORDER BY total_revenue

--Find the top 10 customers who have generated the highest revenue and 3 customers with the fewest orders placed
SELECT TOP 10
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM [gold.fact_sales] f
LEFT JOIN [gold.dim_customers] c
    ON c.customer_key = f.customer_key
GROUP BY 
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;

--The 3 customers with the fewest orders placed

SELECT TOP 3
    c.customer_key,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT order_number) AS total_order
FROM [gold.fact_sales] f
LEFT JOIN [gold.dim_customers] c
    ON c.customer_key = f.customer_key
GROUP BY 
    c.customer_key,
    c.first_name,
    c.last_name
